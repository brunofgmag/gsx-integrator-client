#include "PmdgRouteFile.h"

#include <algorithm>
#include <cctype>
#include <array>
#include <chrono>
#include <fstream>
#include <regex>
#include <system_error>
#include "PmdgOptions.h"

namespace
{
    constexpr auto kFlightplansDir = "Flightplans";
    constexpr auto kRouteExtension = ".rte";
    constexpr auto kGeneratedAtPattern =
        R"(^Generated by SimBrief on (\d{2}) ([A-Z][a-z]{2}) (\d{4}) (\d{2}):(\d{2}) UTC$)";
    constexpr long long kSecondsPerMinute = 60;

    constexpr std::array kMonthNames =
        {"Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"};

    std::string Lowered(const std::string& text)
    {
        std::string lowered = text;
        std::ranges::transform(lowered, lowered.begin(),
                               [](const unsigned char character) { return static_cast<char>(std::tolower(character)); });

        return lowered;
    }

    bool IsRoute(const std::filesystem::path& file)
    {
        return Lowered(file.extension().string()) == kRouteExtension;
    }

    std::optional<unsigned> MonthNumber(const std::string& name)
    {
        const auto found = std::ranges::find(kMonthNames, name);
        if (found == kMonthNames.end())
        {
            return std::nullopt;
        }

        return static_cast<unsigned>(found - kMonthNames.begin()) + 1;
    }

    long long EpochSecondsOf(const std::filesystem::directory_entry& entry)
    {
        std::error_code error;
        const std::filesystem::file_time_type written = entry.last_write_time(error);
        if (error)
        {
            return 0;
        }

        const auto systemTime = std::chrono::clock_cast<std::chrono::system_clock>(written);

        return std::chrono::duration_cast<std::chrono::seconds>(systemTime.time_since_epoch()).count();
    }
}

std::optional<std::filesystem::path> PmdgRouteFile::DirectoryFor(const std::string& aircraftName)
{
    const std::optional<std::filesystem::path> optionsPath = PmdgOptions::PathFor(aircraftName);
    if (!optionsPath.has_value())
    {
        return std::nullopt;
    }

    return optionsPath->parent_path() / kFlightplansDir;
}

bool PmdgRouteFile::NamesPlan(const std::filesystem::path& file,
                              const std::string& origin,
                              const std::string& destination)
{
    if (origin.empty() || destination.empty())
    {
        return false;
    }

    if (!IsRoute(file))
    {
        return false;
    }

    return Lowered(file.stem().string()).starts_with(Lowered(origin + destination));
}

std::optional<long long> PmdgRouteFile::ParseGeneratedAt(const std::string& line)
{
    static const std::regex pattern(kGeneratedAtPattern);

    std::smatch fields;
    if (!std::regex_match(line, fields, pattern))
    {
        return std::nullopt;
    }

    const std::optional<unsigned> month = MonthNumber(fields[2].str());
    const int hour = std::stoi(fields[4].str());
    const int minute = std::stoi(fields[5].str());
    if (!month.has_value() || hour > 23 || minute > 59)
    {
        return std::nullopt;
    }

    const std::chrono::year_month_day date{std::chrono::year{std::stoi(fields[3].str())},
                                           std::chrono::month{*month},
                                           std::chrono::day{static_cast<unsigned>(std::stoi(fields[1].str()))}};
    if (!date.ok())
    {
        return std::nullopt;
    }

    const auto moment = std::chrono::sys_days{date} + std::chrono::hours{hour} + std::chrono::minutes{minute};

    return std::chrono::duration_cast<std::chrono::seconds>(moment.time_since_epoch()).count();
}

std::optional<long long> PmdgRouteFile::GeneratedAt(const std::filesystem::path& file)
{
    std::ifstream stream(file);
    std::string firstLine;
    if (!std::getline(stream, firstLine))
    {
        return std::nullopt;
    }

    if (firstLine.ends_with('\r'))
    {
        firstLine.pop_back();
    }

    return ParseGeneratedAt(firstLine);
}

long long PmdgRouteFile::LatestWrite(const std::filesystem::path& directory)
{
    std::error_code error;
    if (!std::filesystem::is_directory(directory, error))
    {
        return 0;
    }

    long long latest = 0;
    for (const auto& entry : std::filesystem::directory_iterator(directory, error))
    {
        if (!entry.is_regular_file() || !IsRoute(entry.path()))
        {
            continue;
        }

        latest = std::max(latest, EpochSecondsOf(entry));
    }

    return latest;
}

std::optional<std::filesystem::path> PmdgRouteFile::NewestWrittenAfter(const std::filesystem::path& directory,
                                                                       const long long baseline)
{
    std::error_code error;
    if (!std::filesystem::is_directory(directory, error))
    {
        return std::nullopt;
    }

    std::optional<std::filesystem::path> newest;
    long long newestWrite = baseline;
    for (const auto& entry : std::filesystem::directory_iterator(directory, error))
    {
        if (!entry.is_regular_file() || !IsRoute(entry.path()))
        {
            continue;
        }

        if (const long long written = EpochSecondsOf(entry); written > newestWrite)
        {
            newestWrite = written;
            newest = entry.path();
        }
    }

    return newest;
}

void PmdgRouteImport::Restart()
{
    baseline_.reset();
    seen_ = false;
    newerThanTheOfp_ = false;
}

void PmdgRouteImport::Judge(const std::filesystem::path& route,
                            const std::string& origin,
                            const std::string& destination,
                            const long long planEpoch)
{
    const std::optional<long long> generatedAt = PmdgRouteFile::GeneratedAt(route);
    if (!generatedAt.has_value() || planEpoch <= 0)
    {
        seen_ = PmdgRouteFile::NamesPlan(route, origin, destination);

        return;
    }

    const long long age = planEpoch - *generatedAt;
    seen_ = age >= 0 && age < kSecondsPerMinute;
    newerThanTheOfp_ = *generatedAt > planEpoch;
}

void PmdgRouteImport::Observe(const std::optional<std::filesystem::path>& directory,
                              const std::string& origin,
                              const std::string& destination,
                              const long long planEpoch)
{
    seen_ = false;
    newerThanTheOfp_ = false;
    if (!directory.has_value())
    {
        return;
    }

    if (!baseline_.has_value())
    {
        baseline_ = PmdgRouteFile::LatestWrite(*directory);
    }

    if (const std::optional<std::filesystem::path> route = PmdgRouteFile::NewestWrittenAfter(*directory, *baseline_);
        route.has_value())
    {
        Judge(*route, origin, destination, planEpoch);
    }
}
