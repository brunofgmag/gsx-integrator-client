namespace
{
    long long NowEpoch()
    {
        return std::chrono::duration_cast<std::chrono::seconds>(
            std::chrono::system_clock::now().time_since_epoch()).count();
    }

    constexpr long long kHeaderMinute = 1791812760;
    constexpr long long kSecondsIntoTheMinute = 28;
    constexpr auto kHeaderLine = "Generated by SimBrief on 12 Oct 2026 13:46 UTC";
    constexpr auto kHeaderlessLine = "Generated by SimBrief";

    QByteArray HeaderAt(const long long epochMinute)
    {
        const QDateTime moment = QDateTime::fromSecsSinceEpoch(epochMinute, QTimeZone::utc());

        return QByteArray("Generated by SimBrief on ") + moment.toString("dd MMM yyyy HH:mm").toLatin1() + " UTC";
    }

    void WriteFile(const QTemporaryDir& dir, const QString& name, const QByteArray& firstLine = kHeaderlessLine)
    {
        QFile file(dir.filePath(name));
        file.open(QIODevice::WriteOnly);
        file.write(firstLine + "\n");
        file.close();
    }

    void Restamp(const QTemporaryDir& dir, const QString& name, const long long epochSeconds)
    {
        const std::filesystem::path file(dir.filePath(name).toStdWString());
        const auto stamp = std::chrono::system_clock::time_point(std::chrono::seconds(epochSeconds));
        std::filesystem::last_write_time(file, std::chrono::clock_cast<std::chrono::file_clock>(stamp));
    }

    std::filesystem::path PathOf(const QTemporaryDir& dir)
    {
        return std::filesystem::path(dir.path().toStdWString());
    }
}

